def patch_locale(locale: str, data: dict, t: dict) -> None:
    settings = data.setdefault("settings", {})
    history = settings.setdefault("history", {})
    history["loadMore"] = t["history_loadMore"]
    history["loadingMore"] = t["history_loadingMore"]
    history["retryableEmpty"] = t["history_retryableEmpty"]
    history["retryTranscription"] = t["history_retryTranscription"]
    history["retryTranscriptionError"] = t["history_retryTranscriptionError"]
    history["loadError"] = t["history_loadError"]
    history["retry"] = t["history_retry"]

    advanced = settings.setdefault("advanced", {})
    advanced["lazyStreamClose"] = {
        "label": t["lazyStreamClose_label"],
        "description": t["lazyStreamClose_description"],
    }
    acc = advanced.setdefault("acceleration", {})
    acc["whisper"] = {
        "title": t["acc_whisper_title"],
        "description": t["acc_whisper_desc"],
    }
    acc["ort"] = {
        "title": t["acc_ort_title"],
        "description": t["acc_ort_desc"],
    }
    acc["gpuDevice"] = {
        "title": t["acc_gpu_title"],
        "description": t["acc_gpu_desc"],
        "auto": t["acc_gpu_auto"],
    }
    acc["labels"] = {
        "auto": t["acc_auto"],
        "cpu": "CPU",
        "cuda": "CUDA",
        "directml": "DirectML",
        "rocm": "ROCm",
    }

    debug = settings.setdefault("debug", {})
    debug["recordingBuffer"] = {
        "title": t["rec_buf_title"],
        "description": t["rec_buf_desc"],
    }
    kb = debug.setdefault("keyboardImplementation", {})
    backends = kb.setdefault("backends", {})
    backends["tauri"] = t["kb_tauri"]
    backends["nativeKeys"] = t["kb_native"]

    data["overlay"] = {
        "listening": t["overlay_listening"],
        "transcribing": t["overlay_transcribing"],
        "processing": t["overlay_processing"],
        "success": t["overlay_success"],
        "failed": t["overlay_failed"],
    }

    home = data.setdefault("home", {})
    home["loadingMore"] = t["home_loadingMore"]
    if "loadMore" not in home:
        home["loadMore"] = t["history_loadMore"]


def main() -> None:
    for locale, translations in TRANSLATIONS.items():
        path = LOCALES_DIR / locale / "translation.json"
        with path.open(encoding="utf-8") as f:
            data = json.load(f)
        patch_locale(locale, data, translations)
        with path.open("w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"Patched {locale}")


if __name__ == "__main__":
    main()
